import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire, isBuiltin } from 'node:module';
import { build } from 'esbuild';
import { assertSafePath } from '../cli/installations.mjs';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(import.meta.url);
const marker = '// Generated by PolishUp. Edit cli/color*.mjs or cli/palette.mjs; run npm run sync.';
const noticeMarker = 'PolishUp bundled helper notices';

export async function prepareTools({ directory = path.join(projectRoot, 'skills/polishup/scripts'), check = false } = {}) {
  directory = assertSafePath(directory);
  const metadata = JSON.parse(fs.readFileSync(path.join(projectRoot, 'package.json'), 'utf8'));
  const colorRoot = path.resolve(path.dirname(require.resolve('colorjs.io')), '..');
  const colorMetadata = JSON.parse(fs.readFileSync(path.join(colorRoot, 'package.json'), 'utf8'));
  if (metadata.devDependencies?.['colorjs.io'] !== colorMetadata.version) throw new Error('Install the exact locked Color.js development dependency before preparing helpers.');
  const result = await build({
    absWorkingDir: projectRoot, entryPoints: ['cli/color-entry.mjs'],
    outfile: path.join(directory, 'color.mjs'), bundle: true, packages: 'bundle',
    platform: 'node', format: 'esm', target: 'node22', write: false, metafile: true,
    minifySyntax: true, treeShaking: true, legalComments: 'inline', logLevel: 'silent',
    banner: { js: marker },
    define: { __POLISHUP_TOOL_VERSION__: JSON.stringify(metadata.version), __POLISHUP_COLOR_VERSION__: JSON.stringify(colorMetadata.version) },
  });
  if (result.outputFiles.length !== 1) throw new Error('The helper must be a single prepared JavaScript file.');
  const imports = Object.values(result.metafile.outputs).flatMap(output => output.imports);
  if (imports.some(item => !item.external || !isBuiltin(item.path))) throw new Error('Prepared helpers may import Node built-ins only.');
  const notice = `${noticeMarker}\n\nThis helper includes Color.js (colorjs.io) ${colorMetadata.version}.\nSource: https://github.com/color-js/color.js\n\n${fs.readFileSync(path.join(colorRoot, 'LICENSE'), 'utf8').replace(/\r\n/g, '\n')}\n`;
  const outputs = new Map([['color.mjs', result.outputFiles[0].contents], ['NOTICE.txt', Buffer.from(notice)]]);
  const stale = [];
  for (const [name, bytes] of outputs) {
    const file = assertSafePath(path.join(directory, name));
    if (!fs.existsSync(file) || !fs.readFileSync(file).equals(Buffer.from(bytes))) stale.push(name);
    if (!check && fs.existsSync(file)) {
      const expected = name === 'color.mjs' ? marker : noticeMarker;
      if (!fs.readFileSync(file, 'utf8').startsWith(expected)) throw new Error(`Unmanaged helper file: ${file}. Preserve it before preparing tools.`);
    }
  }
  if (check && stale.length) throw new Error(`Missing or stale prepared helpers: ${stale.join(', ')}. Run npm run sync.`);
  if (!check && stale.length) {
    fs.mkdirSync(directory, { recursive: true });
    for (const name of stale) fs.writeFileSync(path.join(directory, name), outputs.get(name));
  }
  return { toolVersion: metadata.version, engineVersion: colorMetadata.version, changed: check ? 0 : stale.length,
    bytes: Object.fromEntries([...outputs].map(([name, bytes]) => [name, bytes.length])) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if (args.length > 1 || args.some(arg => arg !== '--check')) throw new Error('Usage: node scripts/prepare-tools.mjs [--check]');
    console.log(JSON.stringify(await prepareTools({ check: args.includes('--check') }), null, 2));
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
